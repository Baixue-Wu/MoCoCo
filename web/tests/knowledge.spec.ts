test('local editor shows an approved Commons insert on the timeline and exports its credits', async ({ page, request }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.addInitScript(() => localStorage.setItem('mococo.ui_lang', 'zh'))
  await page.goto('http://127.0.0.1:8766/p/sintel-rag/shots')
  await page.getByText('检索与插入外部图片', { exact: true }).click()
  await expect(page.getByRole('button', { name: '已插入 · 撤回', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '确认许可并插入本段', exact: true }).first()).toBeVisible()
  const portrait = page.locator('details img').nth(1)
  await expect.poll(() => portrait.evaluate((img: HTMLImageElement) => img.naturalWidth), { timeout: 15000 }).toBeGreaterThan(0)
  await page.screenshot({ path: '/tmp/mococo-rag-images.png', fullPage: true })
  await page.goto('http://127.0.0.1:8766/p/sintel-rag/cut')
  await expect(page.locator('.clip-block img')).toHaveCount(1)
  await expect(page.locator('.clip-block img')).toHaveAttribute('src', /commons-22488114/)
  const credits = await request.get('http://127.0.0.1:8766/api/projects/sintel-rag/image-credits')
  expect(credits.ok()).toBeTruthy()
  expect(await credits.text()).toContain('David Revoy / Blender Foundation')
  expect(errors).toEqual([])
})

test('finished Sintel commentary loads and chapter buttons seek the actual video', async ({ page }) => {
  test.setTimeout(90000)
  await page.goto('http://127.0.0.1:8767/MoCoCo/#/examples/sintel-analysis/export')
  const video = page.getByLabel('Sintel 深度解析成片')
  await expect(video).toBeVisible()
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.duration), { timeout: 60000 }).toBeGreaterThan(290)
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.videoWidth)).toBe(1280)
  await video.evaluate((v: HTMLVideoElement) => { v.muted = true })
  await page.getByRole('button', { name: /七｜设计资料能说明什么/ }).click()
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.currentTime), { timeout: 20000 }).toBeGreaterThan(189)
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.paused)).toBe(false)
  await expect.poll(() => video.evaluate((v: HTMLVideoElement) => v.readyState), { timeout: 20000 }).toBeGreaterThanOrEqual(2)
  await page.screenshot({ path: '/tmp/sintel-film-player.png', fullPage: false })
  await page.getByText('展开成片解说词', { exact: true }).click()
  await expect(page.getByText('她走过漫长的路，只想找回曾经救过的小龙。', { exact: false }).first()).toBeVisible()
})
