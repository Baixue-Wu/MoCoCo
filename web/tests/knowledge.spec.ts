import { test, expect } from '@playwright/test'

test('analysis uses the same workflow layout as recap and exposes real artifacts in each step', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:8767/MoCoCo/#/examples/sintel-analysis')
  const nav = page.getByRole('navigation', { name: '制作流程' })
  await expect(nav.getByRole('link')).toHaveCount(7)
  await expect(page.getByRole('heading', { name: '原片与素材', exact: true })).toBeVisible()
  await page.locator('.shot-grid button').first().click()
  await expect(page.locator('.example-frame-large')).toBeVisible()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await nav.getByRole('link', { name: '资料检索 · RAG' }).click()
  await expect(page.getByRole('heading', { name: '一次真实 RAG 运行记录' })).toBeVisible()
  await page.getByLabel('筛选摘记（关键词，不调用模型）').fill('不存在的关键词')
  await expect(page.getByRole('status')).toContainText('没有匹配的资料')
  await page.getByRole('button', { name: '表情', exact: true }).click()
  await expect(page.getByRole('heading', { name: /Open Source Goes to Hollywood/ })).toBeVisible()
  await page.getByText('展开检索依据', { exact: true }).first().click()
  await expect(page.locator('blockquote').first()).toContainText('Pant')
  await nav.getByRole('link', { name: '成片文案', exact: true }).click()
  await expect(page.locator('.example-script-paragraph')).toHaveCount(10)
  await page.getByText('查看本段资料依据', { exact: true }).nth(5).click()
  await expect(page.locator('.example-script-paragraph').nth(5)).toContainText('Shashwat Pant')
  await nav.getByRole('link', { name: '镜头与资料图', exact: true }).click()
  await expect(page.getByText('David Revoy / Blender Foundation', { exact: false })).toBeVisible()
  await page.screenshot({ path: '/tmp/sintel-workflow-shots.png', fullPage: false })
  await nav.getByRole('link', { name: '剪辑时间线', exact: true }).click()
  await expect(page.locator('.clip-strip')).toHaveCount(10)
  await expect(page.locator('.clip-block').first()).toContainText('成片')
  await nav.getByRole('link', { name: '配音与字幕', exact: true }).click()
  await expect(page.locator('.timing-table tbody tr')).toHaveCount(10)
  await page.getByText('展开完整字幕与时间码').click()
  await expect(page.locator('pre')).toContainText('她走过漫长的路')
  await expect.poll(() => page.locator('audio').evaluate((a: HTMLAudioElement) => a.duration), { timeout: 30000 }).toBeGreaterThan(260)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await nav.getByRole('link', { name: '剪辑时间线', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.reload()
  await expect(nav.getByRole('link', { name: '剪辑时间线', exact: true })).toHaveClass('active')
  await page.screenshot({ path: '/tmp/sintel-workflow-mobile.png', fullPage: false })
  await page.goto('http://127.0.0.1:8767/MoCoCo/#/examples/sherlock-jr')
  await expect(nav.getByRole('link')).toHaveCount(6)
  await nav.getByRole('link', { name: '文案', exact: true }).click()
  await expect(page.locator('.example-script-paragraph').first()).toBeVisible()
  await nav.getByRole('link', { name: '导出', exact: true }).click()
  await expect(page.locator('video')).toBeVisible()
  expect(errors).toEqual([])
})

